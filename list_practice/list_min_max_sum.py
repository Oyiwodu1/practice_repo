# LIST BUILT-IN FUNCTIONS

# min() finds the smallest value
numbers = [10, 4, 25, 7, 18]
print(min(numbers))

# max() finds the largest value
numbers = [10, 4, 25, 7, 18]
print(max(numbers))

# sum() adds all numbers together
numbers = [10, 4, 25, 7, 18]
print(sum(numbers))

sales = [5000, 2500, 8000, 3000, 4500]
print(min(sales))
print(max(sales))
print(sum(sales))

scores = [45, 78, 92, 33, 67]
total = sum(scores)
number_of_scores = len(scores)
average = total / number_of_scores
print(average)